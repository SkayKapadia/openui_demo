import { listDashboards } from "@/lib/dashboard-store";
import type { Metadata } from "next";
import Link from "next/link";

export const dynamic = "force-dynamic";
export const metadata: Metadata = { title: "Saved dashboards · India Open Data" };

export default async function DashboardsPage() {
  const dashboards = await listDashboards();

  return (
    <div className="live-dash">
      <header className="live-dash__bar">
        <div className="live-dash__titles">
          <nav className="live-dash__crumbs">
            <Link href="/">Chat</Link>
          </nav>
          <h1>Saved dashboards</h1>
        </div>
        <div className="live-dash__stats">
          <span className="live-dash__pill live-dash__pill--live">
            <i /> Stored in Postgres
          </span>
        </div>
      </header>

      {dashboards.length === 0 ? (
        <p className="dash-list">
          No dashboards yet. Ask the chat for a live dashboard, or run <code>npm run db:seed</code>.
        </p>
      ) : (
        <ul className="dash-list">
          {dashboards.map((d) => (
            <li key={d.id}>
              <Link href={`/d/${d.id}`}>
                <strong>{d.title}</strong>
                <small>
                  {d.model === "hand-written" ? "Hand-written sample" : `Generated by ${d.model}`} ·{" "}
                  {new Date(d.updatedAt).toLocaleDateString("en-IN", { dateStyle: "medium" })}
                </small>
              </Link>
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}
